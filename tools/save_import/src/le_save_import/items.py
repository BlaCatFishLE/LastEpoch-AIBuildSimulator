def decode_item(data):
    """Decode one ItemData v6 byte array.

    ``data`` may be a list/tuple/bytes of ints (as stored in the save JSON).
    Returns a dict; ``byte_exact`` says whether the chosen layout consumes
    exactly ``len(data)`` bytes.
    """
    data = [int(b) & 0xFF for b in data]
    n = len(data)
    if n == 0:
        raise DecodeError("empty item data")
    if data[0] != CURRENT_DATA_SERIALISATION_VERSION:
        raise DecodeError(
            f"unsupported ItemData serialisation version {data[0]} (expected 6)")

    item = {
        "format_version": data[0],
        "byte_length": n,
        "instance_id_bytes": data[1:5] if n >= 5 else [],
        "instance_id": None,
        "duplicated": False,
        "tool_generated": False,
        "layout": None,
        "base_type_id": None,
        "base_type_name": None,
        "item_kind": None,
        "sub_type_id": None,
        "rarity": None,
        "rarity_name": None,
        "flags": None,
        "corrupted": False,
        "ruined": False,
        "required_faction": None,
        "always_untradeable": False,
        "faction_rank_requirement": None,
        "implicit_rolls": [],
        "forging_potential": None,
        "forging_potential_type": None,
        "forging_byte": None,
        "state_byte": None,
        "explicit_affix_count": None,
        "has_sealed_affix_channel": False,
        "has_corrupted_affix_channel": False,
        "unique_id": None,
        "unique_rolls": [],
        "legendary_potential_or_weavers_will": None,
        "affixes": [],
        "sealed_affix": None,
        "corrupted_affix": None,
        "primordial_affix": None,
        "gifting_targets": [],
        "game_loader_interpretation": None,
        "consumed_bytes": 0,
        "byte_exact": False,
        "leftover": [],
        "notes": [],
    }

    if n < 7:
        item["consumed_bytes"] = n
        item["leftover"] = data
        item["notes"].append(
            "shorter than every known ItemData v6 form; likely a compact "
            "stackable-list entry, not an ItemData serialisation")
        return item

    item["instance_id"] = _concat_four(data[1] & 0x7F, data[2], data[3], data[4])
    item["duplicated"] = bool(data[1] & 0x80)
    item["instance_id_bytes"] = data[1:5]
    item["tool_generated"] = (data[1:5] == TOOL_INSTANCE_ID_BYTES)
    item["base_type_id"] = data[5]
    item["base_type_name"] = (BASE_TYPE_NAMES.get(data[5])
                              or ITEM_TYPE_NAMES.get(data[5]))
    if data[5] > FIRST_NON_EQUIPPABLE_ITEM_TYPE:
        item["item_kind"] = "non-equippable"
    elif data[5] in IDOL_BASE_TYPES:
        item["item_kind"] = "idol"
    elif data[5] == BLESSING_BASE_TYPE:
        item["item_kind"] = "blessing"
    elif data[5] == IDOL_ALTAR_BASE_TYPE:
        item["item_kind"] = "idol-altar"
    else:
        item["item_kind"] = "equipment"

    if data[5] > FIRST_NON_EQUIPPABLE_ITEM_TYPE:
        _decode_non_equippable(item, data)
    else:
        _decode_equipment(item, data)
    return item


def _gifting_count(rarity_byte: int) -> int:
    return (int(rarity_byte) >> 6) & 0x03


def _read_le_uint64s(data, pos, count):
    out = []
    for k in range(count):
        off = pos + 8 * k
        if off + 8 <= len(data):
            out.append(int.from_bytes(bytes(data[off:off + 8]), "little"))
    return out


def _decode_equipment(item, data):
    """Plain and unique/set/legendary equipment layouts (also used by the
    editor's 'plain' layout for non-equippable base types)."""
    n = len(data)
    item["layout"] = "equipment"
    if n < 12:
        item["consumed_bytes"] = n
        item["leftover"] = data
        item["notes"].append(
            f"equippable item truncated: {n} bytes, need at least 12")
        return
    item["sub_type_id"] = data[6]
    rarity_byte = data[7]
    item["rarity"] = rarity_byte & 0x3F
    item["rarity_name"] = RARITY_NAMES.get(item["rarity"])
    gifting_count = _gifting_count(rarity_byte)
    flags = data[8]
    item["flags"] = flags
    item["corrupted"] = bool(flags & 0x10)
    item["ruined"] = bool(flags & 0x20)
    item["required_faction"] = bool(flags & 0x40)
    item["always_untradeable"] = bool(flags & 0x80)
    item["faction_rank_requirement"] = flags & 0x0F
    item["implicit_rolls"] = data[9:12]

    rarity = item["rarity"]
    if rarity in SPECIAL_RARITIES:
        _decode_unique_payload(item, data)
    else:
        _decode_plain_payload(item, data)
    if not item["consumed_bytes"]:
        return

    # gifting targets appended after the affixes
    affix_end = item["consumed_bytes"]
    item["gifting_targets"] = _read_le_uint64s(data, affix_end, gifting_count)
    if item["gifting_targets"]:
        item["notes"].append(
            f"{len(item['gifting_targets'])} gifting target(s) appended after affixes")
    total = affix_end + 8 * len(item["gifting_targets"])
    item["consumed_bytes"] = min(total, n)
    item["byte_exact"] = total == n
    item["leftover"] = data[total:] if total < n else []
    if not item["byte_exact"]:
        item["notes"].append(
            f"layout consumes {total} of {n} bytes (trailing {n - total})")


def _decode_plain_payload(item, data):
    """Plain/magic/rare/exalted: forging byte + state byte + affixes."""
    n = len(data)
    pos = 12
    if n < pos + 2:
        item["consumed_bytes"] = min(n, pos)
        return
    item["forging_byte"] = data[pos]
    item["forging_potential"] = data[pos] & 0x3F
    item["forging_potential_type"] = data[pos] >> 6
    pos += 1
    state = data[pos]
    pos += 1
    item["state_byte"] = state
    count, has_sealed, has_corrupted = tool_state_split(state)
    item["explicit_affix_count"] = count
    item["has_sealed_affix_channel"] = has_sealed
    item["has_corrupted_affix_channel"] = has_corrupted

    gifts = _gifting_count(data[7])
    available = n - pos - 8 * gifts
    if count * 3 > available:
        item["notes"].append(
            f"state byte announces {count} affixes but only {available} bytes "
            f"remain; truncating")
        count = max(0, available // 3)
    affixes = _read_affix_entries(data[pos:pos + 3 * count])
    item["affix_count"] = len(affixes)
    _assign_channels(item, affixes)
    item["consumed_bytes"] = pos + 3 * item["affix_count"]
    _attach_game_loader_plain(item, state)


def _decode_unique_payload(item, data):
    """Unique / set / legendary: uniqueID + 8 unique rolls + state byte."""
    n = len(data)
    pos = 12
    if n < pos + 10:
        item["consumed_bytes"] = min(n, pos)
        item["notes"].append("truncated unique payload")
        return
    item["unique_id"] = _concat_ushort(data[pos], data[pos + 1])
    item["unique_rolls"] = data[pos + 2:pos + 10]
    pos += 10
    state = data[pos]
    pos += 1
    item["state_byte"] = state
    count, has_sealed, has_corrupted = tool_state_split(state)
    item["explicit_affix_count"] = count
    item["has_sealed_affix_channel"] = has_sealed
    item["has_corrupted_affix_channel"] = has_corrupted
    rarity = item["rarity"]
    if rarity == RARITY_LEGENDARY:
        item["legendary_potential_or_weavers_will"] = None
    else:
        item["legendary_potential_or_weavers_will"] = state & 0x1F
        item["notes"].append(
            "byte 22 low 5 bits are legendaryPotential or weaversWill depending "
            "on the unique definition's LegendaryType; not decidable from bytes")

    gifts = _gifting_count(data[7])
    available = n - pos - 8 * gifts
    length_count = max(0, available // 3)
    if count > length_count:
        item["notes"].append(
            f"state byte announces {count} affixes but {length_count} fit; "
            f"using {length_count} (editor reader is length-driven here)")
        count = length_count
    affixes = _read_affix_entries(data[pos:pos + 3 * count])
    item["affix_count"] = len(affixes)
    _assign_channels(item, affixes)
    item["consumed_bytes"] = pos + 3 * item["affix_count"]
    _attach_game_loader_unique(item, state)


def _read_affix_entries(blob):
    """Decode 3-byte affix entries with pvmReadAffsGen semantics."""
    out = []
    for i in range(0, len(blob) - 2, 3):
        b0, b1, b2 = blob[i], blob[i + 1], blob[i + 2]
        tier0 = (b0 >> 4) & 0x0F
        out.append({
            "affix_id": _concat_ushort(b0 & 0x0F, b1),
            "tier0": tier0,
            "tier": tier0 + 1,
            "roll": b2,
            "channel": "normal",
            "sealed": False,
            "corrupted": False,
            "primordial": tier0 == 7,
        })
    return out


def _assign_channels(item, affixes):
    """Pop sealed first, then corrupted, per pvmDecodeS4."""
    remaining = list(affixes)
    if item["has_sealed_affix_channel"] and remaining:
        sealed = remaining.pop(0)
        sealed["channel"] = "sealed"
        sealed["sealed"] = True
        item["sealed_affix"] = sealed
    if item["has_corrupted_affix_channel"] and remaining:
        corrupted = remaining.pop(0)
        corrupted["channel"] = "corrupted"
        corrupted["corrupted"] = True
        item["corrupted_affix"] = corrupted
    for affix in remaining:
        if affix["tier0"] == 7:
            item["primordial_affix"] = affix
            item["notes"].append(
                "primordial affix (displayed T8) inferred from the tier nibble; "
                "the generator does not flag this channel in the save bytes")
            break
    item["affixes"] = affixes


def _attach_game_loader_plain(item, state):
    """What the retail game's loader would read from the same plain payload."""
    item["game_loader_interpretation"] = {
        "note": "retail game ItemData loader (ISIL); the save was generated by "
                "the editor tool, whose 0x40/0x80 channel bits are swapped "
                "relative to the game",
        "affix_count": state & 0x3F,
        "has_sealed_regular_affix": bool(state & 0x80),
        "sealed_regular_affix_index": 0 if (state & 0x80) else None,
        "has_sealed_affix_from_corruption": bool(state & 0x40),
        "corruption_affix_index": (
            (1 if (state & 0x80) else 0) if (state & 0x40) else None),
        "forging_potential": item["forging_potential"],
        "forging_potential_type": item["forging_potential_type"],
    }


def _attach_game_loader_unique(item, state):
    rarity = item["rarity"]
    if rarity == RARITY_LEGENDARY:
        corrupted = item["corrupted"]
        item["game_loader_interpretation"] = {
            "note": "retail game ItemData loader (ISIL): for legendary items the "
                    "editor's 0x40 sealed flag is read as weaversWill=8 and 0x80 "
                    "as corruption-sealed-last",
            "affix_count": state & 0x07,
            "has_sealed_affix_from_corruption": (
                bool(state >> 7) if corrupted else False),
            "corruption_affix_is_last": bool(state >> 7) if corrupted else False,
            "weavers_will": (None if corrupted else (state >> 3)),
        }
    else:
        item["game_loader_interpretation"] = {
            "note": "retail game ItemData loader (ISIL): unique/set items have no "
                    "special-affix channels; byte 22 >> 5 = affix count, low 5 "
                    "bits = legendaryPotential or weaversWill",
            "affix_count": state >> 5,
            "legendary_potential_or_weavers_will": state & 0x1F,
        }


def _decode_non_equippable(item, data):
    """baseTypeID > 100: either the game's compact layout or the editor's
    generic 'plain' layout."""
    n = len(data)
    item_type = data[5]
    expected_game_len = GAME_NON_EQUIPPABLE_LENGTHS.get(item_type)
    if item_type == 105:
        expected_game_len = 13 + 8 * _gifting_count(data[7]) if n >= 13 else 13
    if expected_game_len is not None and n == expected_game_len:
        item["layout"] = "game-non-equippable"
        _decode_game_non_equippable(item, data)
        return
    if _looks_like_plain_layout(data):
        item["layout"] = "editor-plain-non-equippable"
        _decode_equipment(item, data)
        item["layout"] = "editor-plain-non-equippable"
        item["item_kind"] = "non-equippable"
        item["notes"].append(
            "editor-tool 'plain' layout used for a non-equippable base type "
            "(the retail game would parse this type with a compact payload; see "
            "game_loader_interpretation)")
        item["game_loader_interpretation"] = _game_loader_non_equippable_guess(
            data)
        return
    item["layout"] = "unknown-non-equippable"
    item["consumed_bytes"] = n
    item["leftover"] = data
    item["notes"].append(
        f"no known layout for baseTypeID {item_type} with {n} bytes")


def _looks_like_plain_layout(data):
    """True when the bytes fit the generic plain/unique equipment layout."""
    n = len(data)
    if n < 14:
        return False
    rarity = data[7] & 0x3F
    gifts = _gifting_count(data[7])
    if rarity in SPECIAL_RARITIES:
        if n < 23:
            return False
        return (n - 23 - 8 * gifts) % 3 == 0
    return (n - 14 - 8 * gifts) % 3 == 0


def _decode_game_non_equippable(item, data):
    n = len(data)
    item_type = data[5]
    sub = None
    consumed = n
    if item_type in (101, 107):
        sub = _concat_ushort(data[6], data[7]) if n >= 8 else None
        consumed = 8
    elif item_type in (102, 103, 104, 108, 109):
        sub = data[6] if n >= 7 else None
        consumed = 7
        if item_type == 102 and sub == 7:
            sub = 0
        if item_type == 103 and sub == 4:
            sub = 0
    elif item_type == 105:
        sub = _concat_ushort(data[6], data[7]) if n >= 8 else None
        if n >= 12:
            item["memory_affix_1_id"] = data[8]
            item["memory_affix_1_roll"] = data[9]
            item["memory_affix_2_id"] = data[10]
            item["memory_affix_2_roll"] = data[11]
        gifts = data[12] >> 6 if n >= 13 else 0
        item["gifting_targets"] = _read_le_uint64s(data, 13, gifts)
        consumed = 13 + 8 * len(item["gifting_targets"])
    elif item_type == 106:
        sub = data[6] if n >= 7 else None
        if n >= 15:
            item["resonance_target"] = int.from_bytes(bytes(data[7:15]), "little")
        consumed = 15
    item["sub_type_id"] = sub
    item["consumed_bytes"] = consumed
    item["byte_exact"] = consumed == n
    item["leftover"] = data[consumed:] if consumed < n else []
    if not item["byte_exact"]:
        item["notes"].append(
            f"game non-equippable layout consumes {consumed} of {n} bytes")


def _game_loader_non_equippable_guess(data):
    """Retail-game reading of an editor-plain item with baseTypeID > 100."""
    item_type = data[5]
    out = {"note": "the retail game parses this baseTypeID with a compact "
                   "payload, not the editor's plain layout"}
    if item_type in (101, 107):
        out["consumed_bytes"] = 8
        out["sub_type_id"] = _concat_ushort(data[6], data[7]) if len(data) >= 8 else None
    elif item_type in (102, 103, 104, 108, 109):
        out["consumed_bytes"] = 7
        out["sub_type_id"] = data[6] if len(data) >= 7 else None
    elif item_type == 106:
        out["consumed_bytes"] = 15
        out["sub_type_id"] = data[6] if len(data) >= 7 else None
        out["resonance_target"] = int.from_bytes(bytes(data[7:15]), "little")
    elif item_type == 105:
        out["consumed_bytes"] = 13
        out["sub_type_id"] = _concat_ushort(data[6], data[7]) if len(data) >= 8 else None
    else:
        out["consumed_bytes"] = 6
        out["sub_type_id"] = None
    consumed = out["consumed_bytes"]
    out["trailing_bytes"] = data[consumed:] if len(data) > consumed else []
    return out


