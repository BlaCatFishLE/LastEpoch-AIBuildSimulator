class DecodeError(ValueError):
    """Raised when the byte array cannot be a known ItemData v6 serialisation."""


# ---------------------------------------------------------------------------
# packing helpers (EpochExtensions / pvmReadAffsGen semantics)
# ---------------------------------------------------------------------------
def _concat_ushort(high: int, low: int) -> int:
    return ((high & 0xFF) << 8) | (low & 0xFF)


def _concat_four(a: int, b: int, c: int, d: int) -> int:
    return ((a & 0xFF) << 24) | ((b & 0xFF) << 16) | ((c & 0xFF) << 8) | (d & 0xFF)


def tool_state_split(raw: int):
    """Split a state (affix-count) byte the way the generator does.

    Returns ``(explicit_affix_count, has_sealed_channel, has_corrupted_channel)``.
    Generator (pvmEncodeItem/pvmDecodeS4):
        state = affixCount + 64*sealed + 128*corrupted
        has_corrupted = raw > 128        (strictly greater)
        then if remaining >= 64: sealed, remaining -= 64
    """
    raw = int(raw) & 0xFF
    has_corrupted = raw > 128
    count = raw - 128 if has_corrupted else raw
    has_sealed = count >= 64
    if has_sealed:
        count -= 64
    return count, has_sealed, has_corrupted


def tool_state_byte(affix_count: int, has_sealed: bool, has_corrupted: bool) -> int:
    return (int(affix_count) + (64 if has_sealed else 0)
            + (128 if has_corrupted else 0)) & 0xFF


