def _affix_bytes(affix):
    affix_id = int(affix["affix_id"])
    tier0 = int(affix["tier0"])
    return [(tier0 << 4) | ((affix_id >> 8) & 0x0F),
            affix_id & 0xFF,
            int(affix["roll"]) & 0xFF]


def encode_item(item):
    """Re-serialise a decoded item back to its ``data`` byte list.

    Mirrors the editor's encoder (primary layout) and the game's compact
    non-equippable layouts when the decoder identified that layout.  Used by the
    tests to prove the decode captured every byte (round-trip equality).
    """
    layout = item.get("layout")
    base = int(item["base_type_id"])
    instance = list(item.get("instance_id_bytes") or TOOL_INSTANCE_ID_BYTES)
    instance = (instance + [0, 0, 0, 0])[:4]
    data = [CURRENT_DATA_SERIALISATION_VERSION] + instance

    if layout == "game-non-equippable":
        sub = int(item.get("sub_type_id") or 0)
        if base in (101, 107):
            data += [base, (sub >> 8) & 0xFF, sub & 0xFF]
        elif base in (102, 103, 104, 108, 109):
            data += [base, sub & 0xFF]
        elif base == 105:
            data += [base, (sub >> 8) & 0xFF, sub & 0xFF,
                     int(item.get("memory_affix_1_id") or 0),
                     int(item.get("memory_affix_1_roll") or 0),
                     int(item.get("memory_affix_2_id") or 0),
                     int(item.get("memory_affix_2_roll") or 0),
                     (len(item.get("gifting_targets") or []) & 0x03) << 6]
            for gift in item.get("gifting_targets") or []:
                data += list(int(gift).to_bytes(8, "little"))
        elif base == 106:
            data += [base, sub & 0xFF]
            data += list(int(item.get("resonance_target") or 0).to_bytes(8, "little"))
        else:
            data += [base]
        return data

    # plain or unique payload (equipment, or editor-plain non-equippable)
    sub = int(item.get("sub_type_id") or 0) & 0xFFFF
    if layout == "editor-plain-non-equippable":
        sub &= 0xFF
    flags = int(item.get("flags") or 0) & 0xFF
    implicit = list(item.get("implicit_rolls") or [255, 255, 255])[:3]
    while len(implicit) < 3:
        implicit.append(255)
    rarity = int(item.get("rarity") or 0) & 0x3F
    gifts = list(item.get("gifting_targets") or [])
    gifting_count = len(gifts)

    ordered = []
    if item.get("sealed_affix"):
        ordered.append(item["sealed_affix"])
    if item.get("corrupted_affix"):
        ordered.append(item["corrupted_affix"])
    sealed_obj = item.get("sealed_affix")
    corrupted_obj = item.get("corrupted_affix")
    for affix in item.get("affixes") or []:
        if affix is sealed_obj or affix is corrupted_obj:
            continue
        ordered.append(affix)
    state = tool_state_byte(len(ordered),
                            bool(item.get("has_sealed_affix_channel")),
                            bool(item.get("has_corrupted_affix_channel")))

    if rarity in SPECIAL_RARITIES:
        uid = int(item.get("unique_id") or 0) & 0xFFFF
        unique_rolls = list(item.get("unique_rolls") or [255] * 8)[:8]
        while len(unique_rolls) < 8:
            unique_rolls.append(255)
        data += [base & 0xFF, sub & 0xFF, rarity, flags] + implicit
        data += [(uid >> 8) & 0xFF, uid & 0xFF] + unique_rolls + [state]
    else:
        forging = item.get("forging_byte")
        if forging is None:
            forging = ((item.get("forging_potential") or 0) & 0x3F) | \
                      (((item.get("forging_potential_type") or 0) & 0x03) << 6)
        rarity_byte = rarity | ((gifting_count & 0x03) << 6)
        data += [base & 0xFF, sub & 0xFF, rarity_byte, flags] + implicit
        data += [int(forging) & 0xFF, state]

    for affix in ordered:
        data += _affix_bytes(affix)
    for gift in gifts:
        data += list(int(gift).to_bytes(8, "little"))
    return data


