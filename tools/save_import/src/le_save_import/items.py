"""Last Epoch offline-save ``ItemData`` v6 byte decoder + encoder.

Scope: the ``savedItems[*].data`` byte arrays of a Last Epoch character slot
(``1CHARACTERSLOT_BETA_*``) or stash save.

THE SAVE WE DECODE WAS GENERATED BY A LOCAL SAVE EDITOR
-------------------------------------------------------
The character save (`BlaCFEditor`) was produced by
``<game-install>\\Editor\\lastepochsupertools_v1.3.1``
(a local web app derived from lastechtools).  Its planner JS contains the exact
save reader/writer used to emit these bytes:

* ``pvmEncodeItem`` — the writer that produced the managed items,
* ``pvmDecodeS4`` / ``pvmDecodeItem`` — the matching reader,
* ``pvmBuildSaveFromWire`` — slot/container mapping and the blessing special case.

Extracted copies were kept read-only in the research workspace ``.scratch/save-recon/tool-recon/``;
that workspace is archived outside the repository (see 作者本地迁移对照表（不随公开仓库分发） and
作者本地归档说明（不随公开仓库分发）) and is not needed to decode a save.
They are the **authoritative** interpretation of this save and are what this
module implements as the *primary* decode.  The retail game's own loader differs
in one respect (the two special-affix bits are swapped, see below); that
alternative reading is reported under ``game_loader_interpretation`` so callers
can see both.

Byte layout, serialisation version 6 (absolute offsets; confirmed by the
generator code AND by the game's Il2CPP ``ItemData.setValuesFromSerialisation`` /
``RebuildID`` recovered with Cpp2IL ISIL — see NOTES.md §1):

  Header (all items):
    [0]      format version (6)
    [1..4]   instance id bytes; the editor tool always writes [0,0,127,255]
             (0x7FFF) for items it manages; game-written items carry their own
             id (big-endian 32-bit; bit 7 of [1] = "duplicated" flag)
    [5]      baseTypeID (item type)

  Equippable items (baseTypeID <= 100), and the editor tool's "plain" layout:
    [6]      subTypeID (byte)
    [7]      rarity (low 6 bits) | giftingTargetCount << 6
    [8]      flags: bit4 corrupted, bit5 ruined, bit6 requiredFaction,
             bits0-3 factionRank, bit7 alwaysUntradeable
             (editor's writer: 16 when corrupted OR idol base type 25..33
             OR idol altar 41)
    [9..11]  implicit rolls, 3 raw bytes (editor default 255,255,255)
    then, by rarity class:

    plain / magic / rare / exalted (rarity not 7/8/9):
      [12]     forgingPotential = b & 0x3F ; forgingPotentialType = b >> 6
               (editor's writer: 0 for idol base types 25..33 and for
               blessings (type 34), 20 otherwise)
      [13]     state byte = extraAffixCount
                          + 64  if a sealed affix channel is present
                          + 128 if a corrupted affix channel is present
      [14..]   3 bytes per stored affix, in order: sealedAffix, corruptedAffix,
               primordialAffix, then normal affixes

    unique / set / legendary (rarity 7/8/9):
      [12..13] uniqueID (big-endian uint16)
      [14..21] unique modifier rolls, 8 raw bytes (editor default 255 x8)
      [22]     state byte = extraAffixCount + 64*sealed + 128*corrupted
      [23..]   3 bytes per stored affix (same channel order)

  Affix entry (3 bytes), identical to ``pvmReadAffsGen``:
    b0 = (tier0 << 4) | (affixId >> 8)      # tier0 = tier-1 (0-based)
    b1 = affixId & 0xFF                     # affixId = 12-bit game affix id
    b2 = roll (0..255)

  Special affix channels (editor/generator semantics — authoritative for this save):
    generator pvmEncodeItem:  state = affixes.length
                                       + 64  if w.sealedAffix
                                       + 128 if w.corruptedAffix
    generator pvmDecodeS4:    hasCorrupted = state > 128
                              count = state - 128*hasCorrupted
                              hasSealed  = count >= 64; count -= 64*hasSealed
                              then pop sealed (index 0), then corrupted (next)
    A primordial affix is NOT flagged; it is stored as the first "normal" affix
    (tier nibble 7 => displayed tier 8) and the planner data labels it separately.

  Gifting targets: ``giftingTargetCount = rarityByte >> 6`` little-endian
  uint64 values appended after the affixes (game feature; the editor's writer
  never emits them, and this save has none).

  Non-equippable item types (baseTypeID > 100, ``Item.firstNonEquippableItemType``):
  the GAME's serialiser uses compact payloads:
    101 Shard / 107 WovenEcho : [6..7] subtype uint16 BE            -> 8 bytes
    102 Rune / 103 Glyph / 104 Key / 108 Bag / 109 Lens : [6] subtype byte
                                                                    -> 7 bytes
    105 Memory : subtype uint16 + memoryAffix1ID/Roll + memoryAffix2ID/Roll
                 + gifting byte, gifts                                  -> 13 + 8*n
    106 Resonance : subtype byte + resonanceTarget uint64 LE        -> 15 written
  The editor tool however never implements these compact payloads; it writes the
  generic "plain" layout for every non-managed item type (baseTypeID > 100
  included).  This matters for two items in the character save (cid 91/92,
  type 107 woven echoes) — see NOTES.md §5.

  GAME LOADER vs GENERATOR (the one divergence):
    * generator: 0x40 = sealed affix channel, 0x80 = corrupted affix channel
    * retail game (Il2Cpp ISIL): bit7 (0x80) -> hasSealedRegularAffix (affix #0);
      bit6 (0x40) -> hasSealedAffixFromCorruption (affix #(sealed?1:0)).
      For legendary rarity 9: count = state & 7 and bit7 -> last affix is the
      corruption affix (corrupted items), else state >> 3 = weaversWill.
    The retail game's own writer is the mirror of its loader (sealed -> 0x80,
    corruption -> 0x40).  Because this save is editor-generated, the primary
    decode below follows the generator; ``game_loader_interpretation`` reports
    what the retail game would load from the same bytes.
"""
