def decode_save_items(save_document, *, exclude_legacy_buyback=False):
    """Decode savedItems; explicit build scope excludes v2 shop buyback only."""
    out = []
    for index, entry in enumerate(save_document.get("savedItems") or []):
        container = entry.get("containerID")
        data = entry.get("data") or []
        # 商店回购是非构筑容器；保留原始存档和索引，仅显式排除其旧 v2 数据。
        # 装备/神像/祝福及任何未知版本继续严格拒绝。
        if exclude_legacy_buyback and container == 32 and data and data[0] == 2:
            continue
        if exclude_legacy_buyback and data and data[0] != CURRENT_DATA_SERIALISATION_VERSION:
            raise DecodeError(f"unsupported build ItemData serialisation version {data[0]} (expected 6)")
        decoded = decode_item(data)
        decoded.update({
            "index": index,
            "container_id": container,
            "container_name": CONTAINER_NAMES.get(container, "UNKNOWN"),
            "inventory_position": entry.get("inventoryPosition"),
            "quantity": entry.get("quantity"),
            "save_format_version": entry.get("formatVersion"),
        })
        out.append(decoded)
    return out


def load_save(path):
    """Load an EPOCH save file: 5-byte ASCII 'EPOCH' header + UTF-8 JSON."""
    raw = Path(path).read_bytes()
    if raw[:5] != b"EPOCH":
        raise DecodeError("not an EPOCH save file")
    return json.loads(raw[5:].decode("utf-8"))
